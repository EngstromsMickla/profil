def fix(s):
    s = re.sub(r"\s+", " ", str(s or "")).strip().replace("–", "-").replace("—", "-").replace("’", "'")
    def w(m):
        o = m.group(0); n = FIX.get(o.lower())
        if not n: return o
        return n[0].upper() + n[1:] if o[0].isupper() else n
    s = re.sub(r"[A-Za-zö]+", w, s)
    for a, b in PHRASE: s = s.replace(a, b)
    return s[0].upper() + s[1:] if s else s

def strip_name(d):
    m = re.match(r"^(.{0,90}?)\s?-\s?(?=[A-Z])", d)
    return d[m.end():] if m else d

wb = openpyxl.load_workbook(sys.argv[1])
ws, wd = wb["The worksheet"], wb["Marker definitions"]
domains = [("cv", "Cv", 6, 11), ("mc", "M", 13, 18), ("sp", "S", 20, 22), ("bm", "B", 24, 29), ("cl", "Cl", 31, 37)]
dims = [("ti", "T", "B", "U", "R", "O", "L", 3, 26), ("bd", "B", "E", "V", "S", "P", "M", 30, 50), ("ee", "E", "H", "W", "T", "Q", "N", 54, 80)]
out = {}
for dk, dcode, nameCol, l1, l2, l3, l4, d0, d1 in dims:
    defs = [str(wd[f"C{r}"].value) for r in range(d0, d1 + 1) if wd[f"B{r}"].value]
    i = 0
    out[dk] = {}
    for dom, code, r0, r1 in domains:
        lst = []
        for r in range(r0, r1 + 1):
            if not ws[f"{nameCol}{r}"].value: continue
            lst.append({"id": f"{code}{dcode}{len(lst) + 1}", "name": fix(ws[f"{nameCol}{r}"].value),
                        "definition": fix(strip_name(re.sub(r"\s+", " ", defs[i]).strip())),
                        "levels": [fix(ws[f"{c}{r}"].value) for c in (l1, l2, l3, l4)]})
            i += 1
        out[dk][dom] = lst
    assert i == len(defs)
# Definitionsfliken har Organisational learning och Dynamic capability monitoring i omvänd ordning.
a, b = out["ti"]["cl"][4], out["ti"]["cl"][5]
a["definition"], b["definition"] = b["definition"], a["definition"]
n = sum(len(v) for d in out.values() for v in d.values())
assert n == 72, n
with open(sys.argv[2], "w", encoding="utf-8") as f:
    f.write("// The 72 markers with definitions and four level descriptions (level 1 to 4).\n")
    f.write("// Source: Kafuluma (2026), Beyond Pilots, Linköping University, and the accompanying assessment tool.\n")
    f.write("// Generated by verktyg/las_excel.py. Obvious spelling errors corrected; wording otherwise as in the source.\n")
    f.write("export default " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
print("ok", n)
