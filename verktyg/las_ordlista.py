# Läser ordlistan (Ordlista_Beyond_Pilots_*.xlsx) och skriver publik/innehall/ordlista.js.
# Svensk term = Dans val om det är ifyllt, annars Svenska förslag.
# Varnar om ett bortvalt alternativ (rader med Beslut behövs = Ja) används i de svenska texterna, så att de kan rättas.
# Användning: python3 verktyg/las_ordlista.py Ordlista.xlsx publik/innehall/ordlista.js
import json, re, sys
from pathlib import Path
import openpyxl

def rader(ws):
    rows = list(ws.iter_rows(values_only=True))
    head = [str(h or "").strip() for h in rows[0]]
    for r in rows[1:]:
        d = {head[i]: ("" if v is None else str(v).strip()) for i, v in enumerate(r) if i < len(head)}
        if d.get("ID"): yield d

def sv(d):
    return d.get("Dans val") or d.get("Svenska förslag")

wb = openpyxl.load_workbook(sys.argv[1], read_only=True)
def alt(d):
    return d.get("Alternativ", "") if d.get("Beslut behövs", "").lower() == "ja" else ""
modell = [{"id": d["ID"], "en": d["Engelska"], "sv": sv(d), "enText": d.get("Förklaring på engelska", ""), "svText": d.get("Förklaring på svenska", ""), "alt": alt(d)} for d in rader(wb["Modellen"])]
markorer = [{"id": d["ID"], "en": d["Engelska"], "sv": sv(d), "alt": alt(d)} for d in rader(wb["Markörer"])]
begrepp = [{"id": d["ID"], "en": d["Engelska"], "sv": sv(d), "enText": d.get("Förklaring på engelska", ""), "svText": d.get("Förklaring på svenska", ""), "alt": alt(d)} for d in rader(wb["Begrepp"])]
assert len(markorer) == 72, len(markorer)
for x in modell + markorer + begrepp:
    for k in ("en", "sv", "enText", "svText"):
        if k in x and re.search("[–—]", x[k]): sys.exit(f"Tankstreck i {x['id']} {k}")

ut = {"model": [{k: v for k, v in x.items() if k != "alt"} for x in modell],
      "markers": {x["id"]: {"en": x["en"], "sv": x["sv"]} for x in markorer},
      "concepts": [{k: v for k, v in x.items() if k != "alt"} for x in begrepp]}
Path(sys.argv[2]).write_text(
    "// Bilingual glossary. Generated by verktyg/las_ordlista.py from the reviewed glossary workbook. Do not edit by hand.\n"
    "export default " + json.dumps(ut, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")

# Varningar: bortvalda alternativ som förekommer i svenska texter.
svtext = ""
for f in ("sv.js", "sv-markorer.js"):
    p = Path(sys.argv[2]).with_name(f)
    if p.exists(): svtext += p.read_text(encoding="utf-8").lower()
varn = []
for x in modell + markorer + begrepp:
    for a in re.split(r",\s*", x.get("alt", "")):
        a = re.sub(r"\(.*?\)", "", a).strip().lower()
        if len(a) > 5 and a != x["sv"].lower() and a not in x["sv"].lower() and a in svtext:
            varn.append(f"{x['id']}: vald term '{x['sv']}', men '{a}' förekommer i de svenska texterna")
print(f"ok: {len(modell)} modelltermer, {len(markorer)} markörer, {len(begrepp)} begrepp")
for v in varn: print("Varning:", v)
